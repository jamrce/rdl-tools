def parse_changelog(path: Path) -> tuple[str | None, list[str]]:
    """(date, bullets) from a changelog/v*.md file. Front matter is optional."""
    text = path.read_text(encoding="utf-8")
    date = None
    match = FRONT_MATTER_RE.match(text)
    if match:
        for line in match.group(1).splitlines():
            key, _, value = line.partition(":")
            if key.strip() == "date":
                date = value.strip().strip("\"'") or None
        text = text[match.end() :]
    bullets = [re.sub(r"^[-*]\s+", "", line).strip() for line in text.splitlines() if re.match(r"^[-*]\s+", line)]
    return date, bullets


def pin_release_date(static_dir: Path, version: str, module: ModuleData) -> str | None:
    """Last resort for a historical release's date: the date stamped into its published pin."""
    pin = static_dir / f"v{version}" / "ont" / "ont.ttl"
    if not pin.exists():
        return None
    graph = Graph()
    try:
        graph.parse(pin, format="turtle")
    except Exception:  # a malformed old pin must not break the build
        return None
    ontology = next(graph.subjects(RDF.type, OWL.Ontology), None)
    if ontology is None:
        return None
    source = module.env.get("RELEASE_DATE_SOURCE", "dcterms:modified")
    predicate = DCTERMS.created if source == "dcterms:created" else DCTERMS.modified
    return pick_literal(graph, ontology, predicate)


def collect_releases(module: ModuleData, version: str) -> list[Json]:
    """Every release the repo knows about — changelog files, published pins and the one being cut."""
    changelog_dir = module.module_dir / "changelog"
    static_dir = module.module_dir / "website" / "static"

    versions: set[str] = {version}
    notes: dict[str, list[str]] = {}
    dates: dict[str, str | None] = {}

    if changelog_dir.is_dir():
        for path in sorted(changelog_dir.glob("v*.md")):
            match = CHANGELOG_FILE_RE.match(path.name)
            if not match:
                continue
            found = match.group(1)
            versions.add(found)
            dates[found], notes[found] = parse_changelog(path)

    if static_dir.is_dir():
        for child in static_dir.iterdir():
            if child.is_dir() and re.match(r"^v\d+\.\d+\.\d+$", child.name):
                versions.add(child.name[1:])

    ordered = sorted(versions, key=version_key, reverse=True)
    latest = ordered[0] if ordered else version
    releases = []
    for found in ordered:
        date = dates.get(found)
        if date is None:
            date = module.release_date() if found == version else pin_release_date(static_dir, found, module)
        releases.append(
            {
                "id": found,
                "label": f"v{found}",
                "date": date,
                "isLatest": found == latest,
                "pinIri": module.pin_iri(found),
                "notes": notes.get(found, []),
            }
        )
    return releases


# emitters


def json_text(payload: object) -> str:
    return json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def js_identifier(version: str) -> str:
    return "v" + re.sub(r"[^0-9A-Za-z]", "_", version)


def barrel_text(versions: list[str]) -> str:
    imports = "\n".join(f"import {js_identifier(v)} from './{v}.json';" for v in versions)
    entries = "\n".join(f"  '{v}': {js_identifier(v)}," for v in versions)
    return (
        f"// {GENERATED_BANNER}\n"
        "import site from './site.json';\n"
        "import releases from './releases.json';\n"
        f"{imports}\n"
        "\n"
        "export const byVersion = {\n"
        f"{entries}\n"
        "};\n"
        "\n"
        "export {site, releases};\n"
        "export default {site, releases, byVersion};\n"
    )


