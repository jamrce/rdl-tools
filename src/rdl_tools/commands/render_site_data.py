def escape_mdx_heading(text: str) -> str:
    """Markdown/MDX specials that would otherwise turn a term label into formatting."""
    return re.sub(r"([\\`*_{}\[\]<>])", r"\\\1", text)


def yaml_scalar(text: str) -> str:
    """A double-quoted YAML scalar: a title out of RDF can hold colons, quotes, `#` or newlines."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    escaped = re.sub(r"\s+", " ", escaped).strip()
    return f'"{escaped}"'


def meta_description(text: str) -> str:
    """The first paragraph only: `description` becomes the page's meta tag."""
    first = re.split(r"\n\s*\n", text.strip(), maxsplit=1)[0]
    return re.sub(r"\s+", " ", first).strip()


def reference_mdx_text(module: ModuleData, version: str) -> str:
    """The generated reference page.

    Term headings are real markdown so they land in Docusaurus's `toc` prop, and carry explicit
    `{#LocalName}` anchors, because Docusaurus otherwise lowercases case-preserving anchors.
    """
    lines: list[str | None] = [
        "---",
        f"title: {yaml_scalar(f'{module.title} v{version}')}",
        "hide_title: true",
        f"description: {yaml_scalar(meta_description(module.description))}" if module.description else None,
        "slug: /",
        "toc_max_heading_level: 3",
        "---",
        "",
        f"{{/* {GENERATED_BANNER} Hand-written prose belongs in _intro.mdx. */}}",
        "",
        "import Intro from './_intro.mdx';",
        "import {ReferenceHeader, MetadataSection, TermCard, TermBody} from '@site/src/components/rdl';",
        "",
        "<ReferenceHeader />",
        "",
        "<Intro />",
        "",
        "## Metadata {#metadata}",
        "",
        "<MetadataSection />",
    ]
    for heading, records in (("Classes", module.class_iris), ("Properties", module.property_iris)):
        if not records:
            continue
        anchor = heading.lower()
        lines += ["", f"## {heading} {{#{anchor}}}"]
        for term in records:
            term_id = local_name(str(term))
            # The card frame wraps the heading rather than replacing it: only a real markdown
            # heading reaches the `toc` prop, the left rail and the search index.
            lines += [
                "",
                f'<TermCard id="{term_id}">',
                "",
                f"### {escape_mdx_heading(module.label_for(term))} {{#{term_id}}}",
                "",
                f'<TermBody id="{term_id}" />',
                "",
                "</TermCard>",
            ]
    return "\n".join(line for line in lines if line is not None) + "\n"


def changelog_draft_text(version: str, date: str | None, bullets: list[str]) -> str:
    body = "\n".join(f"- {bullet}" for bullet in bullets) or "- _Describe this release._"
    return (
        "---\n"
        f"date: {date or ''}\n"
        "---\n"
        "\n"
        "<!-- Drafted by `rdl-tools render-site-data --draft-changelog`. Edit freely: the command\n"
        "     never overwrites an existing changelog file. These bullets are published verbatim on\n"
        f"     the Home page's \"What's new in v{version}\" list and on the Versions page. -->\n"
        "\n"
        f"{body}\n"
    )


# changelog diffing


def diff_bullets(previous: Graph, current: Graph, module: NamespaceOwner) -> list[str]:
    """Draft release notes from the graph delta against the previous published pin."""

    def terms(graph: Graph, types: tuple[URIRef, ...]) -> set[str]:
        found = set()
        for rdf_type in types:
            for subject in graph.subjects(RDF.type, rdf_type):
                if isinstance(subject, URIRef) and module.is_internal(str(subject)):
                    found.add(local_name(str(subject)))
        return found

    bullets: list[str] = []
    removed_terms: set[str] = set()
    for kind, types in (("class", CLASS_TYPES), ("property", PROPERTY_TYPES)):
        before, after = terms(previous, types), terms(current, types)
        for name in sorted(after - before):
            bullets.append(f"Added {kind} `{name}`.")
        removed = before - after
        removed_terms |= removed
        for name in sorted(removed):
            bullets.append(f"Removed {kind} `{name}`.")

    def pairs(graph: Graph, predicate: URIRef) -> set[tuple[str, str]]:
        return {
            (local_name(str(s)), local_name(str(o)))
            for s, o in graph.subject_objects(predicate)
            if isinstance(s, URIRef) and isinstance(o, URIRef) and module.is_internal(str(s))
        }

    for predicate, label in (
        (RDFS.domain, "domain"),
        (RDFS.range, "range"),
        (RDFS.subClassOf, "superclass"),
        (RDFS.subPropertyOf, "super-property"),
    ):
        before_pairs, after_pairs = pairs(previous, predicate), pairs(current, predicate)
        for subject, obj in sorted(after_pairs - before_pairs):
            bullets.append(f"`{subject}` gained {label} `{obj}`.")
        # No "lost X" bullet for a subject already reported as removed: it is implied.
        for subject, obj in sorted(before_pairs - after_pairs):
            if subject in removed_terms:
                continue
            bullets.append(f"`{subject}` lost {label} `{obj}`.")

    def definitions(graph: Graph) -> dict[str, str]:
        found: dict[str, str] = {}
        for predicate in (SKOS.definition, RDFS.comment):
            for subject, obj in graph.subject_objects(predicate):
                if isinstance(subject, URIRef) and module.is_internal(str(subject)):
                    found.setdefault(local_name(str(subject)), str(obj))
        return found

    before_defs, after_defs = definitions(previous), definitions(current)
    for name in sorted(set(before_defs) & set(after_defs)):
        if before_defs[name] != after_defs[name]:
            bullets.append(f"Reworded the definition of `{name}`.")

    def shape_rows(graph: Graph) -> set[tuple[str, str]]:
        rows = set()
        for shape in graph.subjects(SH.targetClass, None):
            target = graph.value(shape, SH.targetClass)
            for property_shape in graph.objects(shape, SH.property):
                path = graph.value(property_shape, SH.path)
                if isinstance(target, URIRef) and isinstance(path, URIRef):
                    rows.add((local_name(str(target)), local_name(str(path))))
        return rows

    before_rows, after_rows = shape_rows(previous), shape_rows(current)
    for target, path_name in sorted(after_rows - before_rows):
        bullets.append(f"Added a SHACL constraint on `{target}.{path_name}`.")
    for target, path_name in sorted(before_rows - after_rows):
        bullets.append(f"Removed the SHACL constraint on `{target}.{path_name}`.")
    return bullets


# reporting


def coverage_rows(payload: Json) -> list[Json]:
    rows = []
    for kind, singular in (("classes", "class"), ("properties", "property")):
        for term in payload[kind]:
            rows.append(
                {
                    "id": term["id"],
                    "kind": singular,
                    "definitionSource": term["definitionSource"],
                    "hasDefinition": bool(term["definition"]),
                    "hasExamples": bool(term["examples"]),
                    "hasGuidance": bool(term["guidance"]),
                    "hasScope": bool(term["scope"]),
                }
            )
    return rows


def print_coverage(rows: list[Json]) -> None:
    total = len(rows)
    if not total:
        print("Coverage: no terms found in the module namespace.")
        return

    def pct(key: str) -> str:
        count = sum(1 for row in rows if row[key])
        return f"{count}/{total} ({count * 100 // total}%)"

    fallback = [row["id"] for row in rows if row["definitionSource"] == "rdfs:comment"]
    missing = [row["id"] for row in rows if not row["hasDefinition"]]
    print(f"Annotation coverage over {total} terms (warn only):")
    print(f"  skos:definition / rdfs:comment  {pct('hasDefinition')}")
    print(f"  skos:example                    {pct('hasExamples')}")
    print(f"  skos:editorialNote              {pct('hasGuidance')}")
    print(f"  skos:scopeNote                  {pct('hasScope')}")
    if fallback:
        print(f"  falling back to rdfs:comment:   {', '.join(fallback)}")
    if missing:
        print(f"  no definition at all:           {', '.join(missing)}")


def check_drift(module: ModuleData) -> list[str]:
    """The .env-vs-RDF drift gate. The namespace is the only value duplicated between the two."""
    problems = []
    if not module.namespace_uri:
        problems.append(
            "No vann:preferredNamespaceUri on the owl:Ontology node and no MODULE_NAMESPACE in "
            ".env — the generator cannot tell which terms belong to this module."
        )
    configured_ns = module.env.get("MODULE_NAMESPACE", "")
    if configured_ns and module.namespace_uri and configured_ns != module.namespace_uri:
        problems.append(
            f"MODULE_NAMESPACE={configured_ns!r} in .env disagrees with "
            f"vann:preferredNamespaceUri={module.namespace_uri!r}."
        )
    return problems


# the command


def run(args: argparse.Namespace) -> int:
    module_dir = Path(args.module_dir).resolve()
    module = ModuleData(module_dir, args.version.lstrip("v") if args.version else None)
    version = module.version

    problems = check_drift(module)
    if problems:
        for problem in problems:
            print(f"drift gate: {problem}", file=sys.stderr)
        return 1

    releases = collect_releases(module, version)
    notes: list[str] = next((r["notes"] for r in releases if r["id"] == version), [])
    is_latest = next((r["isLatest"] for r in releases if r["id"] == version), True)
    latest_version = next((r["id"] for r in releases if r["isLatest"]), version)

    payload = module.version_payload(version, module.release_date(), is_latest, notes)
    site = module.site_payload(latest_version)
    rows = coverage_rows(payload)

    generated_dir = module_dir / "website" / "src" / "generated"
    known_versions = sorted(
        {version} | {p.stem for p in generated_dir.glob("*.json") if re.match(r"^\d+\.\d+\.\d+$", p.stem)},
        key=version_key,
        reverse=True,
    )

    # reference.mdx is one working copy: rendering a new version without a doc snapshot of the
    # last one loses it silently. See docs/adrs/ADR-003.
    previous_versions = [v for v in known_versions if v != version]
    if previous_versions:
        previous_latest = max(previous_versions, key=version_key)
        versions_json_path = module_dir / "website" / "versions.json"
        try:
            cut_versions = (
                json.loads(versions_json_path.read_text(encoding="utf-8")) if versions_json_path.exists() else []
            )
        except json.JSONDecodeError:
            cut_versions = []
        if previous_latest not in cut_versions:
            print(
                f"error: rendering v{version} would overwrite website/docs/reference.mdx while "
                f"v{previous_latest}'s docs were never snapshotted as a Docusaurus doc version.",
                file=sys.stderr,
            )
            print(
                f"Run this first, then re-run this command: "
                f"(cd website && npx docusaurus docs:version {previous_latest})",
                file=sys.stderr,
            )
            return 1

    outputs: dict[Path, str] = {
        generated_dir / "site.json": json_text(site),
        generated_dir / "releases.json": json_text(releases),
        generated_dir / f"{version}.json": json_text(payload),
        generated_dir / "index.js": barrel_text(known_versions),
        module_dir / "website" / "docs" / "reference.mdx": reference_mdx_text(module, version),
    }
    accent = module.env.get("ACCENT_COLOR", "").strip()
    accent_path = module_dir / "website" / "src" / "css" / "accent.generated.css"
    if accent:
        outputs[accent_path] = accent_css_text(accent)

    print_coverage(rows)
    for conflict in module.conflicts:
        print(f"warning: {conflict}", file=sys.stderr)

    # Written even under --check: the path is a CI artifact directory, not part of the tree.
    if args.coverage_report:
        report_path = Path(args.coverage_report)
        report_path.parent.mkdir(parents=True, exist_ok=True)
        write_generated(report_path, json_text({"version": version, "terms": rows}))
        print(f"Wrote {report_path}")

    if args.check:
        print(f"--check: generated {len(outputs)} file(s) in memory for v{version}, wrote nothing.")
        return 0

    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        write_generated(path, text)
        print(f"Wrote {path.relative_to(module_dir)}")
    if not accent and accent_path.exists():
        accent_path.unlink()
        print(f"Removed {accent_path.relative_to(module_dir)} (ACCENT_COLOR is unset)")

    if previous_versions:
        print(
            f"\nv{version} will not be reachable on the site until you also run, right now — not "
            f"deferred to the next release:\n"
            f"    (cd website && npx docusaurus docs:version {version})\n"
            'Skipping this leaves it invisible: not staged, not "current," not in the dropdown.'
        )

    if args.draft_changelog:
        draft_changelog(module, version)
    return 0


def draft_changelog(module: ModuleData, version: str) -> None:
    """Write changelog/v{version}.md, but only when it does not already exist."""
    changelog_dir = module.module_dir / "changelog"
    target = changelog_dir / f"v{version}.md"
    static_dir = module.module_dir / "website" / "static"

    bullets: list[str] = []
    previous_pin = find_previous_pin(static_dir, version)
    if previous_pin is not None:
        previous_ttl = previous_pin / "ont" / "ont.ttl"
        if previous_ttl.exists():
            previous = Graph()
            previous.parse(previous_ttl, format="turtle")
            bullets = diff_bullets(previous, module.merged, module)
            print(f"Diffed against {previous_ttl.relative_to(module.module_dir)}: {len(bullets)} bullet(s)")
    else:
        print("No previous pin found — drafting an initial-release note.")
        bullets = [f"Initial release of {module.title}."]

    if target.exists():
        print(f"{target.relative_to(module.module_dir)} exists — leaving it alone. Draft for review:")
        for bullet in bullets:
            print(f"  - {bullet}")
        return
    changelog_dir.mkdir(parents=True, exist_ok=True)
    write_generated(target, changelog_draft_text(version, module.release_date(), bullets))
    print(f"Wrote {target.relative_to(module.module_dir)} — edit the wording before tagging.")
