"""`rdl-tools render-site-data` — everything the Docusaurus site renders, from spec/*.ttl and .env.

    rdl-tools render-site-data --module-dir . --version 0.5.7            # release
    rdl-tools render-site-data --module-dir . --check                    # CI, no writes
    rdl-tools render-site-data --module-dir . --version 0.5.7 --draft-changelog

Outputs, all committed by a release so a published module builds without Python:

    website/src/generated/site.json         config-derived facts and presentation flags
    website/src/generated/releases.json     [{id,label,date,isLatest,pinIri,notes}] newest first
    website/src/generated/{version}.json    one per release — ontology metadata and every term
    website/src/generated/index.js          barrel: {site, releases, byVersion}
    website/src/css/accent.generated.css    only when .env sets ACCENT_COLOR
    website/docs/reference.mdx              the generated reference page — never hand-edited
    changelog/v{version}.md                 a draft, and only when the file is absent

Hand-written prose lives in website/docs/_intro.mdx, which this command never writes.

`--coverage-report <path>` writes the per-term annotation coverage as JSON to a path of its own.
It is written even under `--check`: the target is a CI artifact directory, not part of the tree.
"""

