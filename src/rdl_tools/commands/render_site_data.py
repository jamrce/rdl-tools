# graph reading


def pick_literal(graph: Graph, subject: Node, predicate: Node) -> str | None:
    """One literal for a predicate, preferring @en, then no language, then whatever sorts first."""
    values = [o for o in graph.objects(subject, predicate) if isinstance(o, Literal)]
    if not values:
        return None
    for wanted in ("en", None):
        for value in sorted(values, key=str):
            if (value.language or None) == wanted:
                return str(value)
    return str(sorted(values, key=str)[0])


def pick_literals(graph: Graph, subject: Node, predicate: Node) -> list[str]:
    """Every literal for a predicate, @en only when any @en exists, sorted for byte-stability."""
    values = [o for o in graph.objects(subject, predicate) if isinstance(o, Literal)]
    if not values:
        return []
    english = [v for v in values if (v.language or None) == "en"]
    chosen = english or values
    return sorted({str(v) for v in chosen})


def group(path: str) -> str:
    """Parenthesise a path expression only when composing it would otherwise reassociate it."""
    return f"({path})" if any(sep in path for sep in (" | ", " / ")) else path


def prefixed_name(iri: str, prefixes: list[tuple[str, str]]) -> str:
    """`prefix:localName` for a declared namespace, else the bare IRI."""
    best = ""
    best_prefix = None
    for prefix, uri in prefixes:
        if iri.startswith(uri) and len(uri) > len(best):
            best, best_prefix = uri, prefix
    if best_prefix is None:
        return iri
    return f"{best_prefix}:{iri[len(best) :]}"


# the module view


class ModuleData:
    """Everything read out of spec/ and .env for one module, at one version."""

    def __init__(self, module_dir: Path, version: str | None):
        self.module_dir = module_dir
        self.spec_dir = module_dir / "spec"
        self.env = read_env(module_dir)
        self.graph = merge_ontology(self.spec_dir)
        self.shapes = merge_shapes(self.spec_dir)
        self.merged = self.graph + self.shapes
        self.conflicts: list[str] = []

        ontology = next(self.graph.subjects(RDF.type, OWL.Ontology), None)
        if not isinstance(ontology, URIRef):
            print(f"No owl:Ontology subject found in {self.spec_dir}/*.ttl", file=sys.stderr)
            raise SystemExit(2)
        self.ontology_iri: URIRef = ontology

        self.title = (
            pick_literal(self.graph, ontology, DCTERMS.title) or pick_literal(self.graph, ontology, RDFS.label) or ""
        )
        self.description = (
            pick_literal(self.graph, ontology, DCTERMS.description)
            or pick_literal(self.graph, ontology, RDFS.comment)
            or ""
        )
        self.version = version or pick_literal(self.graph, ontology, OWL.versionInfo) or "0.0.0"
        self.namespace = self._namespace()
        self.prefixes = self._prefixes()
        self.term_label_source = self.env.get("TERM_LABEL_SOURCE", "localName")
        self.external_link_policy = self.env.get("EXTERNAL_LINK_POLICY", "resolve")

        self.class_iris = self._terms_of_type(CLASS_TYPES)
        self.property_iris = self._terms_of_type(PROPERTY_TYPES)
        self.term_iris = set(self.class_iris) | set(self.property_iris)

    # -- config -------------------------------------------------------------

    def _prefixes(self) -> list[tuple[str, str]]:
        """Declared prefixes in declaration order, with this module's own prefix moved last."""
        prefixes = declared_prefixes(ontology_files(self.spec_dir) + shape_files(self.spec_dir))
        module_prefix = self.namespace["prefix"]
        if module_prefix:
            own = [p for p in prefixes if p[0] == module_prefix]
            prefixes = [p for p in prefixes if p[0] != module_prefix] + own
        return prefixes

    def _namespace(self) -> dict[str, str]:
        prefix = pick_literal(self.graph, self.ontology_iri, VANN.preferredNamespacePrefix)
        uri = pick_literal(self.graph, self.ontology_iri, VANN.preferredNamespaceUri)
        return {
            "prefix": prefix or "",
            "uri": uri or self.env.get("MODULE_NAMESPACE", ""),
        }

    @property
    def namespace_uri(self) -> str:
        return self.namespace["uri"]

    @property
    def major_iri(self) -> str:
        authority = self.env.get("W3ID_AUTHORITY", "")
        return f"https://w3id.org/{authority}/{self.env.get('MODULE_SLUG', '')}/v0/ont"

    def pin_iri(self, version: str) -> str:
        """The immutable pin for a version, always from config: a derived module's ontology IRI
        sits under its upstream authority, not this module's."""
        return self.major_iri.replace("/v0/ont", f"/v{version}/ont")

    @property
    def static_base_url(self) -> str:
        """Site-relative base a download link resolves from, whatever page or origin serves it.

        Never the w3id pin IRI: that is a redirect target for RDF clients, not a static path.
        """
        base = self.env.get("WEBSITE_BASE_URL") or f"/{self.env.get('MODULE_SLUG', '')}/"
        return base if base.endswith("/") else base + "/"

    # -- terms --------------------------------------------------------------

    def _terms_of_type(self, types: tuple[URIRef, ...]) -> list[URIRef]:
        found = set()
        for rdf_type in types:
            for subject in self.graph.subjects(RDF.type, rdf_type):
                if isinstance(subject, URIRef) and self.is_internal(str(subject)):
                    found.add(subject)
        return sorted(found, key=lambda s: local_name(str(s)).lower())

    def is_internal(self, iri: str) -> bool:
        return bool(self.namespace_uri) and iri.startswith(self.namespace_uri)

    def label_for(self, iri: URIRef) -> str:
        name = local_name(str(iri))
        if self.term_label_source == "rdfsLabel" and self.is_internal(str(iri)):
            return pick_literal(self.graph, iri, RDFS.label) or name
        return name

    def ref(self, iri: URIRef, via: URIRef | None = None) -> Json:
        """A `ref` as the JSON schema defines it: identity, display label and where it links."""
        iri_str = str(iri)
        internal = self.is_internal(iri_str)
        href: str | None
        if internal:
            href = f"#{local_name(iri_str)}"
        elif self.external_link_policy == "resolve":
            href = iri_str
        else:
            href = None
        return {
            "id": local_name(iri_str),
            "label": self.label_for(iri),
            "iri": iri_str,
            "href": href,
            "external": not internal,
            "via": prefixed_name(str(via), self.prefixes) if via is not None else None,
        }

    def sorted_refs(self, iris: Iterable[URIRef]) -> list[Json]:
        return [self.ref(i) for i in sorted(set(iris), key=lambda s: local_name(str(s)).lower())]

    def definition_of(self, term: URIRef) -> tuple[str, str | None]:
        """skos:definition wins, rdfs:comment is the fallback; the source is reported."""
        definition = pick_literal(self.graph, term, SKOS.definition)
        if definition is not None:
            return definition, "skos:definition"
        comment = pick_literal(self.graph, term, RDFS.comment)
        if comment is not None:
            return comment, "rdfs:comment"
        return "", None

    def is_term_reference(self, iri: URIRef) -> bool:
        """True when an object IRI names a term rather than metadata about one."""
        iri_str = str(iri)
        if self.is_internal(iri_str):
            return iri_str in {str(t) for t in self.term_iris}
        return not any(iri_str.startswith(ns) for ns in METADATA_NAMESPACES)

    def used_by(self, term: URIRef, exclude: set[str]) -> list[Json]:
        """Named terms pointing at this one, minus refs that already have their own block."""
        found = set()
        for predicate in USED_BY_PREDICATES:
            for subject in self.merged.subjects(predicate, term):
                if not isinstance(subject, URIRef) or subject == term:
                    continue
                # Blank property shapes are skipped: Used By lists named terms only.
                if (subject in self.term_iris or not self.is_internal(str(subject))) and str(subject) not in exclude:
                    found.add(subject)
        return self.sorted_refs(found)

    def refers_to(self, term: URIRef, exclude: set[str]) -> list[Json]:
        """Term-valued objects of this term's own triples, each tagged with the predicate used."""
        found: dict[str, Json] = {}
        for predicate, obj in sorted(self.graph.predicate_objects(term), key=lambda po: (str(po[0]), str(po[1]))):
            if predicate in REFERS_TO_SKIP or not isinstance(obj, URIRef):
                continue
            if obj == term or str(obj) in exclude:
                continue
            if not self.is_term_reference(obj):
                continue
            assert isinstance(predicate, URIRef)
            found.setdefault(str(obj), self.ref(obj, via=predicate))
        return [found[key] for key in sorted(found, key=lambda i: local_name(i).lower())]

    def path_text(self, node: Node | None, depth: int = 0) -> str:
        """SPARQL-style text for a SHACL path expression: `^isPartOf`, `a / b`, `a | b`, `a+`.

        A bare IRI renders as the term's own label; anything else is a blank node with no other
        way to reach the reader.
        """
        if isinstance(node, URIRef):
            return self.label_for(node)
        if depth > 8 or node is None:  # a malformed path must not recurse forever
            return "…"
        if self.shapes.value(node, RDF.first) is not None:
            return " / ".join(group(self.path_text(item, depth + 1)) for item in self.shapes.items(node))
        inverse = self.shapes.value(node, SH.inversePath)
        if inverse is not None:
            return f"^{group(self.path_text(inverse, depth + 1))}"
        alternative = self.shapes.value(node, SH.alternativePath)
        if alternative is not None:
            return " | ".join(self.path_text(item, depth + 1) for item in self.shapes.items(alternative))
        for predicate, suffix in PATH_MODIFIERS:
            inner = self.shapes.value(node, predicate)
            if inner is not None:
                return f"{group(self.path_text(inner, depth + 1))}{suffix}"
        return "…"

    def constraints_for(self, cls: URIRef) -> list[Json]:
        """One row per sh:property of every sh:NodeShape targeting this class.

        `property` is a linkable ref only when the path is a bare IRI; `path` always carries the
        display text. `severity` is reported only when it is not SHACL's sh:Violation default.
        """
        rows: list[Json] = []
        for shape in self.shapes.subjects(SH.targetClass, cls):
            for property_shape in self.shapes.objects(shape, SH.property):
                path = self.shapes.value(property_shape, SH.path)
                if path is None:
                    continue
                range_node = None
                for predicate in (SH["class"], SH.datatype, SH.node):
                    candidate = self.shapes.value(property_shape, predicate)
                    if isinstance(candidate, URIRef):
                        range_node = candidate
                        break
                severity = self.shapes.value(property_shape, SH.severity)
                rows.append(
                    {
                        "property": self.ref(path) if isinstance(path, URIRef) else None,
                        "path": self.path_text(path),
                        "range": self.ref(range_node) if range_node is not None else None,
                        "cardinality": self._cardinality(property_shape),
                        "severity": (
                            local_name(str(severity))
                            if isinstance(severity, URIRef) and severity != SH.Violation
                            else None
                        ),
                        "message": pick_literal(self.shapes, property_shape, SH.message),
                    }
                )
        rows.sort(key=lambda row: (str(row["path"]).lower(), row["cardinality"] or ""))
        return rows

    def _cardinality(self, property_shape: Node) -> str | None:
        """`min..max`, or None when the shape declares neither — `0..*` would overstate it."""
        minimum = self.shapes.value(property_shape, SH.minCount)
        maximum = self.shapes.value(property_shape, SH.maxCount)
        if minimum is None and maximum is None:
            return None
        low = int(minimum) if isinstance(minimum, Literal) else 0
        high = int(maximum) if isinstance(maximum, Literal) else "*"
        return f"{low}..{high}"

    def property_cardinality(self, prop: URIRef) -> str | None:
        """The chip beside a property heading. Omitted, and reported, when shapes disagree."""
        found = set()
        for property_shape in self.shapes.subjects(SH.path, prop):
            declared = self._cardinality(property_shape)
            if declared is not None:
                found.add(declared)
        if len(found) == 1:
            return found.pop()
        if len(found) > 1:
            self.conflicts.append(
                f"{local_name(str(prop))}: conflicting SHACL cardinalities {sorted(found)} — chip omitted"
            )
        return None

    # -- assembled records --------------------------------------------------

    def class_record(self, cls: URIRef) -> Json:
        definition, source = self.definition_of(cls)
        super_classes = [o for o in self.graph.objects(cls, RDFS.subClassOf) if isinstance(o, URIRef)]
        sub_classes = [s for s in self.graph.subjects(RDFS.subClassOf, cls) if isinstance(s, URIRef)]
        own_blocks = {str(i) for i in list(super_classes) + list(sub_classes)}
        return {
            "id": local_name(str(cls)),
            "label": self.label_for(cls),
            "iri": str(cls),
            "definition": definition,
            "definitionSource": source,
            "examples": pick_literals(self.graph, cls, SKOS.example),
            "guidance": pick_literals(self.graph, cls, SKOS.editorialNote),
            "scope": pick_literals(self.graph, cls, SKOS.scopeNote),
            "superClasses": self.sorted_refs(super_classes),
            "subClasses": self.sorted_refs(sub_classes),
            "constraints": self.constraints_for(cls),
            "usedBy": self.used_by(cls, exclude={str(i) for i in sub_classes}),
            "refersTo": self.refers_to(cls, exclude=own_blocks),
        }

    def property_record(self, prop: URIRef) -> Json:
        definition, source = self.definition_of(prop)
        domain = next((o for o in self.graph.objects(prop, RDFS.domain) if isinstance(o, URIRef)), None)
        range_ = next((o for o in self.graph.objects(prop, RDFS.range) if isinstance(o, URIRef)), None)
        super_properties = [o for o in self.graph.objects(prop, RDFS.subPropertyOf) if isinstance(o, URIRef)]
        own_blocks = {str(i) for i in super_properties}
        own_blocks |= {str(i) for i in (domain, range_) if i is not None}
        return {
            "id": local_name(str(prop)),
            "label": self.label_for(prop),
            "iri": str(prop),
            "definition": definition,
            "definitionSource": source,
            "examples": pick_literals(self.graph, prop, SKOS.example),
            "guidance": pick_literals(self.graph, prop, SKOS.editorialNote),
            "scope": pick_literals(self.graph, prop, SKOS.scopeNote),
            "domain": self.ref(domain) if domain is not None else None,
            "range": self.ref(range_) if range_ is not None else None,
            "subPropertyOf": self.sorted_refs(super_properties),
            "symmetric": (prop, RDF.type, OWL.SymmetricProperty) in self.graph,
            "cardinality": self.property_cardinality(prop),
            "usedBy": self.used_by(prop, exclude=set()),
            "refersTo": self.refers_to(prop, exclude=own_blocks),
        }

    def license_record(self) -> Json | None:
        license_iri = next(self.graph.objects(self.ontology_iri, DCTERMS.license), None)
        if license_iri is None:
            return None
        if isinstance(license_iri, Literal):
            return {"label": str(license_iri), "href": None}
        label = local_name(str(license_iri))
        return {"label": label[:-5] if label.endswith(".html") else label, "href": str(license_iri)}

    def release_date(self) -> str | None:
        source = self.env.get("RELEASE_DATE_SOURCE", "dcterms:modified")
        predicate = {"dcterms:modified": DCTERMS.modified, "dcterms:created": DCTERMS.created}.get(
            source, DCTERMS.modified
        )
        return pick_literal(self.graph, self.ontology_iri, predicate)

    def downloads(self, version: str) -> list[Json]:
        """Only formats present on disk get a button, not every format DOWNLOAD_FORMATS asks for."""
        formats = [f.strip() for f in self.env.get("DOWNLOAD_FORMATS", "ttl").split(",") if f.strip()]
        pin_dir = self.module_dir / "website" / "static" / f"v{version}" / "ont"
        base = f"{self.static_base_url}v{version}/ont"
        downloads = [
            {"label": DOWNLOAD_LABELS.get(fmt, fmt.upper()), "href": f"{base}/ont.{fmt}"}
            for fmt in formats
            if fmt in DOWNLOAD_LABELS and (pin_dir / f"ont.{fmt}").exists()
        ]
        # render-docs copies spec/*.generated.ttl into every artifact tree as ledger.ttl.
        if (pin_dir / "ledger.ttl").exists():
            downloads.append({"label": "Ledger", "href": f"{base}/ledger.ttl"})
        return downloads

    def version_payload(self, version: str, date: str | None, is_latest: bool, notes: list[str]) -> Json:
        version_iri = next(self.graph.objects(self.ontology_iri, OWL.versionIRI), None)
        prior = next(self.graph.objects(self.ontology_iri, OWL.priorVersion), None)
        return {
            "id": version,
            "label": f"v{version}",
            "date": date,
            "isLatest": is_latest,
            "ontology": {
                "iri": str(self.ontology_iri),
                "versionIri": str(version_iri) if version_iri is not None else self.pin_iri(version),
                "priorVersionIri": str(prior) if prior is not None else None,
                "majorIri": self.major_iri,
                "pinIri": self.pin_iri(version),
                "title": self.title,
                "description": self.description,
                "publisher": pick_literal(self.graph, self.ontology_iri, DCTERMS.publisher),
                "created": pick_literal(self.graph, self.ontology_iri, DCTERMS.created),
                "modified": pick_literal(self.graph, self.ontology_iri, DCTERMS.modified),
                "versionInfo": pick_literal(self.graph, self.ontology_iri, OWL.versionInfo),
                "license": self.license_record(),
                "namespace": self.namespace,
            },
            "namespaces": [{"prefix": p, "uri": u} for p, u in self.prefixes],
            "counts": {"classes": len(self.class_iris), "properties": len(self.property_iris)},
            "downloads": self.downloads(version),
            "changelog": notes,
            "classes": [self.class_record(c) for c in self.class_iris],
            "properties": [self.property_record(p) for p in self.property_iris],
        }

    def site_payload(self, latest_version: str) -> Json:
        return {
            "moduleSlug": self.env.get("MODULE_SLUG", ""),
            "title": self.title,
            "tagline": self.description,
            "brandSubtitle": self.env.get("BRAND_SUBTITLE", "Reference Data Library"),
            "majorIri": self.major_iri,
            "pinIriPattern": self.major_iri.replace("/v0/ont", "/v{version}/ont"),
            "latestVersion": latest_version,
            "latestVersionLabel": f"v{latest_version}",
            "defaultColorMode": self.env.get("DEFAULT_COLOR_MODE", "light"),
            "termLabelSource": self.term_label_source,
            "externalLinkPolicy": self.external_link_policy,
            "showFooter": self.env.get("SHOW_FOOTER", "false").lower() == "true",
            "accentColor": self.env.get("ACCENT_COLOR", ""),
        }


